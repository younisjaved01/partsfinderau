import type {
  PartCategory,
  PartPosition,
  PartSide,
  QualityTier,
} from '@/types';

/**
 * A template describes a *kind* of part. The generator (parts.ts) expands each
 * template across its applicable vehicles and quality tiers to build the
 * catalogue of 100+ parts. Aliases are the informal terms a user might type —
 * this is what lets "shockey", "rubber thing" or "filter box" resolve to the
 * correct catalogue term (§25).
 */
export interface PartTemplate {
  key: string;
  name: string;
  category: PartCategory;
  /** Canonical catalogue term used when normalising messy queries. */
  canonicalTerm: string;
  aliases: string[];
  position: PartPosition;
  side: PartSide;
  /** OEM base price band in AUD — actual price varies by tier. */
  basePrice: number;
  specs: Record<string, string>;
  /** Vehicle ids this template fits, or 'all'. */
  vehicles: string[] | 'all';
  /** Quality tiers to generate for this template. */
  tiers: QualityTier[];
  /** Illustrative icon key. */
  image: string;
}

